<#
.SYNOPSIS
    统计 C# 源码中的后缀非空断言(null-forgiving `!`)处数,按 nullable-migration-13/14/21 的分类分桶。

.DESCRIPTION
    复刻 nullable-migration-21 的口径,使「还剩多少处断言」可复现:
      - 预处理:剔除注释与字符串/字符字面量(逐字符状态机,含 @"" 与 $"",保留换行以维持行号)
      - 匹配:后缀形态 `[\w\)\]]!(?!=)`——不含前缀逻辑非(`!x`)与不等号(`!=`)
      - 排除:生成文件(*.Designer.cs、RikaichanAutogenerated.cs),与 spec.md「影响」节一致
    分桶与 issues/13 的分类同构,但不做逐站点判定(站点锚点仍是 bang-sites.md):
      null! / Argument 可选字段 / list[i]! 索引后断言 / (x as T)! / JumpTo 族 / 残差类
    残差类再按接收者形态分桶(bare-local / X.Member! / F(...)! / X![i] / other-expr / default!),
    与 bang-sites.md 的构成表同构。

    已知局限:不做跨方法的不变量判定;`Argument` 可选字段按属性名清单近似(该类的票面处数
    本身有三种口径,见 issues/14「口径与清单」),故只用于比较趋势与验收「是否归零」,
    不作为逐站点对账的依据。

.EXAMPLE
    pwsh -File tracker/nullable-migration/tools/count-bang-sites.ps1
    # 传数组参数必须走 -Command:-File 模式会把 Emuera,Emuera.Tests 并成一个字符串,两个路径都被跳过
    pwsh -NoProfile -Command "& './tracker/nullable-migration/tools/count-bang-sites.ps1' -Path Emuera,Emuera.Tests"
    pwsh -File tracker/nullable-migration/tools/count-bang-sites.ps1 -ListResidual | Select-Object -First 40
#>
[CmdletBinding()]
param(
	# 相对仓库根的扫描目录
	[string[]]$Path = @('Emuera'),
	# 逐条列出残差类站点(文件:行:片段)
	[switch]$ListResidual,
	# 跳过去除注释与字面量,直接在原文上匹配(对账用)
	[switch]$Raw,
	# 仓库根,默认由脚本位置上溯三级
	[string]$Root
)

$ErrorActionPreference = 'Stop'

if (-not $Root) {
	$Root = (Resolve-Path (Join-Path $PSScriptRoot '..\..\..')).Path
}

# Argument 派生类的可空字段:构造器按分支决定是否写入,故读取点常带 `!`
$argumentFieldPattern = '^\.(Def|Mouse|Term|Terms|Value|Values|Opt|Nameb|Namem|RowArgs|SubNames|CallFunc|PluginArgs)$'
$jumpToPattern = '\.(JumpTo|JumpToEndCatch|ParentLabelLine)$'

# 剔除注释与字面量,换行原样保留(否则站点行号会漂移)
function Remove-CSharpTrivia {
	param([string]$Text)

	$sb = [System.Text.StringBuilder]::new($Text.Length)
	$i = 0
	$n = $Text.Length
	while ($i -lt $n) {
		$c = $Text[$i]
		if ($c -eq '/' -and $i + 1 -lt $n -and $Text[$i + 1] -eq '/') {
			while ($i -lt $n -and $Text[$i] -ne "`n") { $i++ }
			continue
		}
		if ($c -eq '/' -and $i + 1 -lt $n -and $Text[$i + 1] -eq '*') {
			$i += 2
			while ($i + 1 -lt $n -and -not ($Text[$i] -eq '*' -and $Text[$i + 1] -eq '/')) {
				if ($Text[$i] -eq "`n") { [void]$sb.Append("`n") }
				$i++
			}
			$i = [Math]::Min($i + 2, $n)
			continue
		}
		# 逐字字符串 @"..." 与插值逐字字符串 $@"...":内部 "" 表示一个引号
		$dollarVerbatim = ($c -eq '$' -and $i + 2 -lt $n -and $Text[$i + 1] -eq '@' -and $Text[$i + 2] -eq '"')
		$verbatim = ($c -eq '@' -and $i + 1 -lt $n -and $Text[$i + 1] -eq '"')
		if ($dollarVerbatim -or $verbatim) {
			$i += if ($dollarVerbatim) { 3 } else { 2 }
			while ($i -lt $n) {
				if ($Text[$i] -eq '"') {
					if ($i + 1 -lt $n -and $Text[$i + 1] -eq '"') { $i += 2; continue }
					$i++
					break
				}
				if ($Text[$i] -eq "`n") { [void]$sb.Append("`n") }
				$i++
			}
			[void]$sb.Append('""')
			continue
		}
		if ($c -eq '"' -or ($c -eq '$' -and $i + 1 -lt $n -and $Text[$i + 1] -eq '"')) {
			$i += if ($c -eq '$') { 2 } else { 1 }
			while ($i -lt $n) {
				if ($Text[$i] -eq '\') { $i += 2; continue }
				if ($Text[$i] -eq '"') { $i++; break }
				if ($Text[$i] -eq "`n") { [void]$sb.Append("`n") }
				$i++
			}
			[void]$sb.Append('""')
			continue
		}
		if ($c -eq "'") {
			$i++
			while ($i -lt $n) {
				if ($Text[$i] -eq '\') { $i += 2; continue }
				if ($Text[$i] -eq "'") { $i++; break }
				$i++
			}
			[void]$sb.Append("''")
			continue
		}
		[void]$sb.Append($c)
		$i++
	}
	return $sb.ToString()
}

function Get-LineNumber {
	param([string]$Text, [int]$Index)
	$count = 0
	for ($k = 0; $k -lt $Index; $k++) { if ($Text[$k] -eq "`n") { $count++ } }
	return $count + 1
}

# `(x as T)!`:断言作用在强制转换表达式上,故 `!` 之前是转换表达式的收尾(通常是 `)`)。
# 两个分支语义不同,故不合并:站点字符是 `)` 时取**与之配对**的那对括号(闭合的转换表达式);
# 否则取站点左侧最近一个**未闭合**的 `(`(包围式)。合并成一个「找最近的 `(`」会让
# `(x as Foo)!.Bar!` 的成员断言被误判成 as 转换。
# 与 issues/14「口径与清单」记载的 63 处不同:那个数字来自旧匹配式的嵌套 `as` 重复计数,
# 真实站点数按 issues/14 的复核结论为 53 处(票面记 51)。
function Test-AsCast {
	param([string]$Text, [int]$Idx)

	if ($Text[$Idx] -eq ')') {
		# 取与该 `)` 配对的那对括号,看其内是否出现 ` as `
		$depth = 0
		for ($j = $Idx; $j -ge 0; $j--) {
			if ($Text[$j] -eq ')') { $depth++ }
			elseif ($Text[$j] -eq '(') {
				$depth--
				if ($depth -eq 0) { return ($Text.Substring($j, $Idx - $j + 1) -match '\bas\s') }
			}
		}
		return $false
	}
	# 兜底:站点左侧最近一个未闭合的 `(`,其内出现 ` as `
	$depth = 0
	for ($j = $Idx; $j -ge 0; $j--) {
		if ($Text[$j] -eq ')') { $depth++ }
		elseif ($Text[$j] -eq '(') {
			if ($depth -eq 0) { return ($Text.Substring($j, $Idx - $j + 1) -match '\bas\s') }
			$depth--
		}
	}
	return $false
}

$generatedNames = @('RikaichanAutogenerated.cs')

$buckets = [ordered]@{
	'null!'                  = 0
	'Argument 可选字段'       = 0
	'list[i]! 索引后断言'     = 0
	'(x as T)!'              = 0
	'JumpTo 族'               = 0
	'残差类'                  = 0
}
$residualBuckets = [ordered]@{
	'bare/local'  = 0
	'X.Member!'   = 0
	'F(...)!'     = 0
	'X![i]'       = 0
	'other-expr'  = 0
	'default!'    = 0
}
$perFile = @{}
$sites = [System.Collections.Generic.List[string]]::new()
$totalAll = 0

foreach ($scope in $Path) {
	$scopePath = Join-Path $Root $scope
	if (-not (Test-Path $scopePath)) { Write-Warning "跳过不存在的路径: $scope"; continue }
	$files = Get-ChildItem $scopePath -Recurse -Filter *.cs -File |
		Where-Object {
			$_.Name -notlike '*.Designer.cs' -and
			$generatedNames -notcontains $_.Name -and
			$_.FullName -notmatch '[\\/](bin|obj)[\\/]' # 构建产物里的拷贝不算源码
		}

	$total = 0
	$scopeBuckets = [ordered]@{}
	foreach ($k in $buckets.Keys) { $scopeBuckets[$k] = 0 }

	foreach ($file in $files) {
		$text = Get-Content $file.FullName -Raw
		if (-not $Raw) { $text = Remove-CSharpTrivia -Text $text }
		$fileCount = 0
		foreach ($m in [regex]::Matches($text, '([\w\)\]])!(?!=)')) {
			$fileCount++
			$total++
			$totalAll++
			$idx = $m.Index # 匹配到的最后一个字符(标识符尾、`)` 或 `]`),`!` 在其后一位
			$idStart = $idx
			while ($idStart -gt 0) {
				$pc = $text[$idStart - 1]
				if ([char]::IsLetterOrDigit($pc) -or $pc -eq '_') { $idStart-- } else { break }
			}
			$id = $text.Substring($idStart, $idx - $idStart + 1)
			$before = if ($idStart -gt 0) { $text[$idStart - 1] } else { ' ' }
			$preceding = $text.Substring(0, $idStart)
			$isMember = $before -eq '.' -or
				($before -eq '?' -and $idStart -ge 2 -and $text[$idStart - 2] -eq '.') -or
				($before -eq '!' -and $idStart -ge 2 -and $text[$idStart - 2] -eq '.')
			$memberName = if ($isMember) { ".$id" } else { '' }
			$after = $text.Substring($idx + 2)
			$isIndexed = $after.TrimStart().StartsWith('[')
			# 站点左侧若有一个未闭合的 `(`、其内出现 ` as `,即为 `(x as T)!`
			$isAsCast = Test-AsCast -Text $text -Idx $idx
			$endsWithBracket = $text[$idx] -eq ']'

			# 与 issues/13 同构的分类,顺序即优先级
			if ($id -eq 'null') {
				$scopeBuckets['null!']++
			}
			elseif ($isMember -and $memberName -match $argumentFieldPattern) {
				$scopeBuckets['Argument 可选字段']++
			}
			elseif ($isMember -and $memberName -match $jumpToPattern) {
				$scopeBuckets['JumpTo 族']++
			}
			elseif ($isAsCast) {
				$scopeBuckets['(x as T)!']++
			}
			elseif ($endsWithBracket) {
				$scopeBuckets['list[i]! 索引后断言']++
			}
			else {
				$scopeBuckets['残差类']++
				# 残差子桶:与 bang-sites.md 的构成表同构
				$lastChar = $text[$idx]
				if ($id -eq 'default') { $residualBuckets['default!']++ }
				elseif ($isIndexed) { $residualBuckets['X![i]']++ }
				elseif ($lastChar -eq ')') { $residualBuckets['F(...)!']++ }
				elseif ($isMember) { $residualBuckets['X.Member!']++ }
				elseif ($id -match '^[A-Za-z_]\w*$') { $residualBuckets['bare/local']++ }
				else { $residualBuckets['other-expr']++ }

				if ($ListResidual) {
					$line = Get-LineNumber -Text $text -Index $idx
					$rel = $file.FullName.Substring($Root.Length + 1)
					$from = [Math]::Max(0, $idx - 40)
					$snippet = ($text.Substring($from, [Math]::Min(60, $text.Length - $from)) -replace '\s+', ' ')
					$sites.Add("$rel`:$line`: $snippet")
				}
			}
		}
		if ($fileCount -gt 0) {
			$rel = $file.FullName.Substring($Root.Length + 1)
			$perFile[$rel] = $fileCount
		}
	}

	"== $scope =="
	"  口径                : $(if ($Raw) { '原始(未剥注释与字面量)' } else { '剥注释与字面量' })"
	"  文件数(排除生成文件): $($files.Count)"
	"  后缀断言总数        : $total"
	foreach ($k in $scopeBuckets.Keys) { "  {0,-22}: {1}" -f $k, $scopeBuckets[$k] }
	if ($Path.Count -gt 1) {
		foreach ($k in @($buckets.Keys)) { $buckets[$k] += $scopeBuckets[$k] }
	}
	""
}

if ($Path.Count -gt 1) {
	"== 合计 =="
	"  后缀断言总数: $totalAll"
	foreach ($k in $buckets.Keys) { "  {0,-22}: {1}" -f $k, $buckets[$k] }
	""
}

"== 残差类接收者分桶 =="
foreach ($k in $residualBuckets.Keys) { "  {0,-12}: {1}" -f $k, $residualBuckets[$k] }
""

"== 后缀断言文件分布(前 15) =="
$perFile.GetEnumerator() | Sort-Object -Property Value -Descending | Select-Object -First 15 |
	ForEach-Object { "  {0,4}  {1}" -f $_.Value, $_.Key }

if ($ListResidual) {
	""
	"== 残差类站点(共 $($sites.Count)) =="
	$sites
}
